// Builds the light language loader (lang.js) and one dictionary file per language (lang/<code>.js)
// from i18n.js, which stays the single source to edit (DICTS). Hebrew needs no file.
// Run: node tools/build-lang.js   (the build-lang workflow also runs it on every push that changes i18n.js)
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.join(__dirname,'..');
const src=fs.readFileSync(path.join(root,'i18n.js'),'utf8');
const lines=src.split('\n');
const di=lines.findIndex(l=>/^\s*var DICTS=\{/.test(l));
if(di<0)throw new Error('DICTS line not found');
const DICTS=Function('return '+lines[di].trim().replace(/^var DICTS=/,'').replace(/;\s*$/,''))();
const h=s=>crypto.createHash('sha1').update(s).digest('hex').slice(0,10);
const V={};
fs.mkdirSync(path.join(root,'lang'),{recursive:true});
for(const k of Object.keys(DICTS)){
  const body='window.__I18N=window.__I18N||{};window.__I18N['+JSON.stringify(k)+']='+JSON.stringify(DICTS[k])+';window.__i18nGo&&window.__i18nGo();\n';
  fs.writeFileSync(path.join(root,'lang',k+'.js'),body);V[k]=h(body);
}
// engine = i18n.js with the dictionary line replaced by a loader; the translating part runs once the file arrives
const heRet=lines.findIndex(l=>/^\s*if\(lang==='he'\)return;/.test(l));
const end=lines.lastIndexOf('})();');
if(heRet<0||end<0||!(heRet<di&&di<end))throw new Error('unexpected i18n.js layout');
let head=lines.slice(0,heRet+1).join('\n');
// picker: Hebrew + English, the rest under "more languages (download)"
head=head.replace(/for\(var k in LANGS\)\{var o=document\.createElement\('option'\);o\.value=k;o\.textContent=LANGS\[k\];if\(k===lang\)o\.selected=true;b\.appendChild\(o\)\}/,
 "var g=null;for(var k in LANGS){var o=document.createElement('option');o.value=k;o.textContent=LANGS[k]+(BASE[k]?'':' ⬇');if(k===lang)o.selected=true;if(BASE[k])b.appendChild(o);else{if(!g){g=document.createElement('optgroup');g.label='⬇ More languages · שפות נוספות';b.appendChild(g)}g.appendChild(o)}}");
if(head.indexOf('BASE[k]')<0)throw new Error('picker pattern not found');
head=head.replace("var RTL={he:1,ar:1};","var RTL={he:1,ar:1};var BASE={he:1,en:1};");
const bodyLines=lines.slice(heRet+1,end).filter((l,i)=>i+heRet+1!==di).join('\n');
const out='/* GENERATED by tools/build-lang.js from i18n.js — do not edit here; edit DICTS in i18n.js and rebuild. */\n'+head+'\n'+
'  var LV='+JSON.stringify(V)+';\n'+
'  window.__i18nGo=function(){if(window.__i18nDone||!window.__I18N||!window.__I18N[lang])return;window.__i18nDone=1;go()};\n'+
'  if(!LV[lang])return;\n'+
'  var LSRC=(function(){var s=document.currentScript&&document.currentScript.src||"";return s.replace(/lang\\.js(\\?.*)?$/,"")})()+"lang/"+lang+".js?v="+LV[lang];\n'+
'  var LW=0;if(document.readyState==="loading"){try{document.write(\'<script src="\'+LSRC+\'"><\\/script>\');LW=1}catch(_){}}\n'+
'  if(!LW){var s=document.createElement("script");s.src=LSRC;(document.head||document.documentElement).appendChild(s)}\n'+
'  function go(){\n  var DICTS=window.__I18N;\n'+bodyLines+'\n  }\n  window.__i18nGo();\n})();\n';
fs.writeFileSync(path.join(root,'lang.js'),out);
const lv=h(out);
for(const f of ['index.html','events.html']){
  const p=path.join(root,f);let t=fs.readFileSync(p,'utf8');
  const n=t.replace(/<script src="(?:i18n|lang)\.js\?v=[^"]*"><\/script>/,'<script src="lang.js?v='+lv+'"></script>');
  if(n===t&&t.indexOf('lang.js?v='+lv)<0)throw new Error('script tag not found in '+f);
  fs.writeFileSync(p,n);
}
console.log('lang.js',out.length,'bytes; files',Object.keys(V).map(k=>k+':'+fs.statSync(path.join(root,'lang',k+'.js')).size).join(' '));
